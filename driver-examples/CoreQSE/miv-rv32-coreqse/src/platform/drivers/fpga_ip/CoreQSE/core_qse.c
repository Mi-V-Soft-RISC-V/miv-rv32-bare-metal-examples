/*******************************************************************************
 * Null parameters with appropriate type definitions.
 */
#define NULL_INSTANCE               (( QSE_instance_t * ) 0)
#define NULL_TX_CONFIG              (( QSE_tx_config_t * ) 0)
#define NULL_RX_CONFIG              (( QSE_rx_config_t * ) 0)
#define NULL_PAUSE_CONFIG           (( QSE_pause_config_t * ) 0)
#define NULL_TX_STATS               (( QSE_tx_stats_t * ) 0)
#define NULL_RX_STATS               (( QSE_rx_stats_t * ) 0)
#define NULL_U8                     (( uint8_t * ) 0)
#define NULL_U16                    (( uint16_t * ) 0)
#define NULL_U32                    (( uint32_t * ) 0)
#define NULL_CONST_U8               (( const uint8_t * ) 0)

#define DISABLE                     ( 0u )
#define ENABLE                      ( 1u )

/*******************************************************************************
 * Local constants.
 */
#define QSE_MAC_ADDR_LEN            ( 6u )
#define QSE_ETH_HDR_LEN             ( 14u )
#define QSE_FCS_LEN                 ( 4u )
#define QSE_PAD_TO_LEN              ( 60u )
#define QSE_VER_RESERVED_MASK       ( 0x0000FFFFuL )
#define QSE_BROADCAST_BYTE          ( 0xFFu )
#define QSE_BYTE_MASK               ( 0xFFu )
#define QSE_BYTE_SHIFT              ( 8u )
#define QSE_NO_FAILED_OFFSET        ( 0xFFFFFFFFuL )
#define QSE_PREAMBLE_SIZE_DEFAULT   ( 0u )
#define QSE_LINK_SETTLE_LOOPS       ( 100000u )

/*******************************************************************************
 * Reset values checked by QSE_self_test().
 */
#define QSE_RESET_MAC_TX_CFG        COREQSE_REG_MAP_MAC_TX_CFG_REG_RESET_VALUE
#define QSE_RESET_MAC_RX_CFG        COREQSE_REG_MAP_MAC_RX_CFG_REG_RESET_VALUE

/*******************************************************************************
 * MAC_ADDR_UPPER byte placement.
 *
 * User guide DS50004157A section 6.68 describes MAC_ADDR_UPPER as the "MAC
 * address upper 16 bits" and lists:
 *     Bits 15:8 - MAC ADDR BYTE 5[7:0]   MAC address upper 16 bits [15:8]
 *     Bits 15:8 - MAC ADDR BYTE 4[7:0]   MAC address upper 16 bits [7:0]
 *
 * The second entry repeats "Bits 15:8" but its description says "[7:0]", so
 * byte 4 occupies bits 7:0 and byte 5 occupies bits 15:8. That is the layout
 * used here.
 *
 * The autogenerated header inherits the same typo: it defines both
 * MAC_ADDR_UPPER_MAC_ADDR_BYTE_4_SHIFT and _BYTE_5_SHIFT as 8, and its
 * REG_RW_MASK of 0x0001FE00 describes an 8-bit field at bit 9 rather than the
 * 16-bit field two address bytes require. The generated shifts are therefore
 * not used. Verify with QSE_set_mac_addr() followed by QSE_get_mac_addr()
 * before relying on unicast filtering.
 */
#define QSE_MAC_ADDR_BYTE4_SHIFT    ( 0u )
#define QSE_MAC_ADDR_BYTE5_SHIFT    ( 8u )

/*******************************************************************************
 * Helpers for building register fields from the autogenerated shift and
 * no-shift mask definitions.
 */
#define QSE_FIELD( REG, FIELD, VALUE )                                        \
    ( ( ( (uint32_t)(VALUE) ) &                                               \
        COREQSE_REG_MAP_##REG##_##FIELD##_NS_MASK )                           \
      << COREQSE_REG_MAP_##REG##_##FIELD##_SHIFT )

#define QSE_MASK( REG, FIELD )                                                \
    ( ( (uint32_t)COREQSE_REG_MAP_##REG##_##FIELD##_NS_MASK )                 \
      << COREQSE_REG_MAP_##REG##_##FIELD##_SHIFT )

/*******************************************************************************
 * QSE_init()
 */
uint8_t
QSE_init
(
    QSE_instance_t * this_qse,
    addr_t           base_addr
)
{
    uint8_t status = QSE_ERR_PARAM;
    uint8_t idx;

    HAL_ASSERT( this_qse != NULL_INSTANCE );
    HAL_ASSERT( base_addr != 0u );

    if( ( this_qse != NULL_INSTANCE ) && ( base_addr != 0u ) )
    {
        this_qse->base_address = base_addr;

        for( idx = 0u; idx < QSE_MAC_ADDR_LEN; idx++ )
        {
            this_qse->mac_addr[ idx ] = 0u;
        }

        /* No PHY is associated until QSE_attach_mdio() is called. Designs with
         * no PHY, such as the 2.5 Gbps SMA loopback design, never call it, and
         * the QSE_phy_* functions then report QSE_ERR_NOT_SUPPORTED rather than
         * appearing to succeed.
         */
        this_qse->mdio_base_address = 0u;
        this_qse->phy_addr          = 0u;

        /* Cache the current configuration so later read-modify-write operations
         * preserve fields this driver does not own.
         */
        this_qse->tx_cfg_shadow = HAL_get_32bit_reg( this_qse->base_address,
                                              COREQSE_REG_MAP_MAC_TX_CFG );

        this_qse->rx_cfg_shadow = HAL_get_32bit_reg( this_qse->base_address,
                                              COREQSE_REG_MAP_MAC_RX_CFG );

        /* Both enable bits are set at reset, so the MAC is already running.
         * Quiesce it so that configuration is applied cleanly.
         */
        this_qse->tx_cfg_shadow &= ~QSE_MASK( MAC_TX_CFG, MAC_TX_EN );
        this_qse->rx_cfg_shadow &= ~QSE_MASK( MAC_RX_CFG, MAC_RX_EN );

        HAL_set_32bit_reg( this_qse->base_address,
                           COREQSE_REG_MAP_MAC_TX_CFG,
                           this_qse->tx_cfg_shadow );

        HAL_set_32bit_reg( this_qse->base_address,
                           COREQSE_REG_MAP_MAC_RX_CFG,
                           this_qse->rx_cfg_shadow );

        status = QSE_OK;
    }

    return ( status );
}

/*******************************************************************************
 * QSE_get_default_tx_cfg()
 */
uint8_t
QSE_get_default_tx_cfg
(
    QSE_tx_config_t * cfg
)
{
    uint8_t status = QSE_ERR_PARAM;

    HAL_ASSERT( cfg != NULL_TX_CONFIG );

    if( cfg != NULL_TX_CONFIG )
    {
        cfg->fcs_insert_mode  = ENABLE;
        cfg->fcs_stomp_mode   = DISABLE;
        cfg->fcs_error_inject = DISABLE;

        /* The user guide states MAC_TX_PAD_EN is only valid when
         * MAC_TX_FCS_INS is clear. The default inserts the FCS, so padding
         * must default off; the MAC enforces the minimum frame size itself.
         */
        cfg->pad_enable       = DISABLE;

        cfg->ipg_count        = QSE_IPG_CNT_STANDARD;
        cfg->max_tx_pkt_len   = COREQSE_FRAME_LEN_MAX;

        /* Standard preamble. The custom preamble requires an optional block, so
         * leaving this at zero keeps the defaults valid on every IP build.
         */
        cfg->preamble_size    = QSE_PREAMBLE_SIZE_DEFAULT;
        cfg->preamble_content = 0u;

        status = QSE_OK;
    }

    return ( status );
}

/*******************************************************************************
 * QSE_get_default_rx_cfg()
 */
uint8_t
QSE_get_default_rx_cfg
(
    QSE_rx_config_t * cfg
)
{
    uint8_t status = QSE_ERR_PARAM;

    HAL_ASSERT( cfg != NULL_RX_CONFIG );

    if( cfg != NULL_RX_CONFIG )
    {
        /* Strip the FCS so software sees payload only. */
        cfg->fcs_remove     = ENABLE;
        cfg->pad_remove     = DISABLE;
        cfg->max_rx_pkt_len = COREQSE_FRAME_LEN_MAX;
        cfg->preamble_size  = QSE_PREAMBLE_SIZE_DEFAULT;

        status = QSE_OK;
    }

    return ( status );
}

/*******************************************************************************
 * QSE_tx_cfg_set()
 */
uint8_t
QSE_tx_cfg_set
(
    QSE_instance_t        * this_qse,
    const QSE_tx_config_t * cfg
)
{
    uint8_t  status = QSE_ERR_PARAM;
    uint32_t reg_value;

    HAL_ASSERT( this_qse != NULL_INSTANCE );
    HAL_ASSERT( cfg != NULL_TX_CONFIG );

    if( ( this_qse != NULL_INSTANCE ) && ( cfg != NULL_TX_CONFIG ) &&
        ( cfg->ipg_count >= QSE_IPG_CNT_MIN ) &&
        ( cfg->ipg_count <= QSE_IPG_CNT_MAX ) &&
        ( cfg->preamble_size <= QSE_PREAMBLE_SIZE_MAX ) &&
        ( cfg->max_tx_pkt_len != 0u ) )
    {
        status = QSE_OK;

#if ( COREQSE_CFG_TX_PREAMBLE == 0u )
        /* The custom preamble block was not generated, so a non-default
         * preamble size would silently have no effect.
         */
        if( cfg->preamble_size != QSE_PREAMBLE_SIZE_DEFAULT )
        {
            status = QSE_ERR_NOT_SUPPORTED;
        }
#endif

        if( status == QSE_OK )
        {
            /* Preserve the transmit enable state. */
            reg_value = this_qse->tx_cfg_shadow &
                        QSE_MASK( MAC_TX_CFG, MAC_TX_EN );

            reg_value |= QSE_FIELD( MAC_TX_CFG, MAC_TX_IFG_CNT,
                                    cfg->ipg_count );

            reg_value |= QSE_FIELD( MAC_TX_CFG, MAC_TX_MAX_PKT_LEN,
                                    cfg->max_tx_pkt_len );

            if( cfg->fcs_stomp_mode != DISABLE )
            {
                reg_value |= QSE_MASK( MAC_TX_CFG, MAC_TX_FCS_STOMP );
            }

            if( cfg->fcs_error_inject != DISABLE )
            {
                reg_value |= QSE_MASK( MAC_TX_CFG, MAC_TX_FCS_ERR );
            }

            if( cfg->fcs_insert_mode != DISABLE )
            {
                reg_value |= QSE_MASK( MAC_TX_CFG, MAC_TX_FCS_INS );
            }

            if( cfg->pad_enable != DISABLE )
            {
                reg_value |= QSE_MASK( MAC_TX_CFG, MAC_TX_PAD_EN );
            }

            /* MAC_TX_PREAMBLE_EN selects the custom preamble, which is only
             * meaningful when a size was requested.
             */
            if( cfg->preamble_size != QSE_PREAMBLE_SIZE_DEFAULT )
            {
                reg_value |= QSE_MASK( MAC_TX_CFG, MAC_TX_PREAMBLE_EN );
            }

            reg_value |= QSE_FIELD( MAC_TX_CFG, MAC_TX_PREAMBLE_WCM1,
                                    cfg->preamble_size );

            HAL_set_32bit_reg( this_qse->base_address,
                               COREQSE_REG_MAP_MAC_TX_CFG, reg_value );

            this_qse->tx_cfg_shadow = reg_value;

#if ( COREQSE_CFG_TX_PREAMBLE != 0u )
            if( cfg->preamble_size != QSE_PREAMBLE_SIZE_DEFAULT )
            {
                HAL_set_32bit_reg( this_qse->base_address,
                                   COREQSE_REG_MAP_MAC_TX_PRE_LOWER,
                                   cfg->preamble_content );
            }
#endif
        }
    }

    return ( status );
}

/*******************************************************************************
 * QSE_rx_cfg_set()
 */
uint8_t
QSE_rx_cfg_set
(
    QSE_instance_t        * this_qse,
    const QSE_rx_config_t * cfg
)
{
    uint8_t  status = QSE_ERR_PARAM;
    uint32_t reg_value;

    HAL_ASSERT( this_qse != NULL_INSTANCE );
    HAL_ASSERT( cfg != NULL_RX_CONFIG );

    if( ( this_qse != NULL_INSTANCE ) && ( cfg != NULL_RX_CONFIG ) &&
        ( cfg->preamble_size <= QSE_PREAMBLE_SIZE_MAX ) &&
        ( cfg->max_rx_pkt_len != 0u ) &&
        /* MAC_RX_PAD_REMOVAL is only valid when MAC_RX_FCS_REMOVE is set. */
        ( ( cfg->pad_remove == DISABLE ) || ( cfg->fcs_remove != DISABLE ) ) )
    {
        status = QSE_OK;

#if ( COREQSE_CFG_RX_PREAMBLE == 0u )
        if( cfg->preamble_size != QSE_PREAMBLE_SIZE_DEFAULT )
        {
            status = QSE_ERR_NOT_SUPPORTED;
        }
#endif

        if( status == QSE_OK )
        {
            /* Preserve the receive enable state and the Wake-on-LAN bit, which
             * is owned by QSE_wol_enable() and QSE_wol_disable().
             */
            reg_value = this_qse->rx_cfg_shadow &
                        ( QSE_MASK( MAC_RX_CFG, MAC_RX_EN ) |
                          QSE_MASK( MAC_RX_CFG, WOL_EN ) );

            if( cfg->pad_remove != DISABLE )
            {
                reg_value |= QSE_MASK( MAC_RX_CFG, MAC_RX_PAD_REMOVAL );
            }

            if( cfg->fcs_remove != DISABLE )
            {
                reg_value |= QSE_MASK( MAC_RX_CFG, MAC_RX_FCS_RMV );
            }

            reg_value |= QSE_FIELD( MAC_RX_CFG, MAC_RX_MAX_PKT_LEN,
                                    cfg->max_rx_pkt_len );

            reg_value |= QSE_FIELD( MAC_RX_CFG, MAC_RX_PREAMBLE_WCM1,
                                    cfg->preamble_size );

            HAL_set_32bit_reg( this_qse->base_address,
                               COREQSE_REG_MAP_MAC_RX_CFG, reg_value );

            this_qse->rx_cfg_shadow = reg_value;
        }
    }

    return ( status );
}

/*******************************************************************************
 * QSE_set_mac_addr()
 */
uint8_t
QSE_set_mac_addr
(
    QSE_instance_t * this_qse,
    const uint8_t  * mac_addr
)
{
    uint8_t  status = QSE_ERR_PARAM;
    uint32_t lower;
    uint32_t upper;
    uint8_t  idx;

    HAL_ASSERT( this_qse != NULL_INSTANCE );
    HAL_ASSERT( mac_addr != NULL_CONST_U8 );

    if( ( this_qse != NULL_INSTANCE ) && ( mac_addr != NULL_CONST_U8 ) )
    {
        /* Bytes 0 to 3, byte 0 first on the wire. */
        lower = QSE_FIELD( MAC_ADDR_LOWER, MAC_ADDR_BYTE_0, mac_addr[ 0u ] ) |
                QSE_FIELD( MAC_ADDR_LOWER, MAC_ADDR_BYTE_1, mac_addr[ 1u ] ) |
                QSE_FIELD( MAC_ADDR_LOWER, MAC_ADDR_BYTE_2, mac_addr[ 2u ] ) |
                QSE_FIELD( MAC_ADDR_LOWER, MAC_ADDR_BYTE_3, mac_addr[ 3u ] );

        /* Bytes 4 and 5. See the QSE_MAC_ADDR_BYTE4_SHIFT comment above. */
        upper = ( ( (uint32_t)mac_addr[ 4u ] & QSE_BYTE_MASK )
                    << QSE_MAC_ADDR_BYTE4_SHIFT ) |
                ( ( (uint32_t)mac_addr[ 5u ] & QSE_BYTE_MASK )
                    << QSE_MAC_ADDR_BYTE5_SHIFT );

        HAL_set_32bit_reg( this_qse->base_address,
                           COREQSE_REG_MAP_MAC_ADDR_LOWER, lower );

        HAL_set_32bit_reg( this_qse->base_address,
                           COREQSE_REG_MAP_MAC_ADDR_UPPER, upper );

        for( idx = 0u; idx < QSE_MAC_ADDR_LEN; idx++ )
        {
            this_qse->mac_addr[ idx ] = mac_addr[ idx ];
        }

        status = QSE_OK;
    }

    return ( status );
}

/*******************************************************************************
 * QSE_get_mac_addr()
 */
uint8_t
QSE_get_mac_addr
(
    const QSE_instance_t * this_qse,
    uint8_t              * mac_addr
)
{
    uint8_t  status = QSE_ERR_PARAM;
    uint32_t lower;
    uint32_t upper;

    HAL_ASSERT( this_qse != NULL_INSTANCE );
    HAL_ASSERT( mac_addr != NULL_U8 );

    if( ( this_qse != NULL_INSTANCE ) && ( mac_addr != NULL_U8 ) )
    {
        lower = HAL_get_32bit_reg( this_qse->base_address,
                                   COREQSE_REG_MAP_MAC_ADDR_LOWER );

        upper = HAL_get_32bit_reg( this_qse->base_address,
                                   COREQSE_REG_MAP_MAC_ADDR_UPPER );

        mac_addr[ 0u ] = (uint8_t)
            ( ( lower >> COREQSE_REG_MAP_MAC_ADDR_LOWER_MAC_ADDR_BYTE_0_SHIFT )
              & QSE_BYTE_MASK );
        mac_addr[ 1u ] = (uint8_t)
            ( ( lower >> COREQSE_REG_MAP_MAC_ADDR_LOWER_MAC_ADDR_BYTE_1_SHIFT )
              & QSE_BYTE_MASK );
        mac_addr[ 2u ] = (uint8_t)
            ( ( lower >> COREQSE_REG_MAP_MAC_ADDR_LOWER_MAC_ADDR_BYTE_2_SHIFT )
              & QSE_BYTE_MASK );
        mac_addr[ 3u ] = (uint8_t)
            ( ( lower >> COREQSE_REG_MAP_MAC_ADDR_LOWER_MAC_ADDR_BYTE_3_SHIFT )
              & QSE_BYTE_MASK );
        mac_addr[ 4u ] = (uint8_t)
            ( ( upper >> QSE_MAC_ADDR_BYTE4_SHIFT ) & QSE_BYTE_MASK );
        mac_addr[ 5u ] = (uint8_t)
            ( ( upper >> QSE_MAC_ADDR_BYTE5_SHIFT ) & QSE_BYTE_MASK );

        status = QSE_OK;
    }

    return ( status );
}

/*******************************************************************************
 * QSE_get_wire_length()
 */
uint8_t
QSE_get_wire_length
(
    const QSE_instance_t * this_qse,
    uint16_t               payload_len,
    uint16_t             * wire_len,
    uint16_t             * rx_len
)
{
    uint8_t  status = QSE_ERR_PARAM;
    uint32_t tx_cfg;
    uint32_t rx_cfg;
    uint16_t len;

    HAL_ASSERT( this_qse != NULL_INSTANCE );
    HAL_ASSERT( payload_len != 0u );

    if( ( this_qse != NULL_INSTANCE ) && ( payload_len != 0u ) )
    {
        tx_cfg = HAL_get_32bit_reg( this_qse->base_address,
                                    COREQSE_REG_MAP_MAC_TX_CFG );

        rx_cfg = HAL_get_32bit_reg( this_qse->base_address,
                                    COREQSE_REG_MAP_MAC_RX_CFG );

        len = payload_len;

        /* The MAC pads frames whose payload is shorter than 46 bytes, giving a
         * 60-byte frame before any FCS. This happens either when
         * MAC_TX_PAD_EN is set, or when MAC_TX_FCS_INS is set and the MAC
         * therefore owns the frame tail.
         */
        if( ( ( ( tx_cfg & QSE_MASK( MAC_TX_CFG, MAC_TX_PAD_EN  ) ) != 0u ) ||
              ( ( tx_cfg & QSE_MASK( MAC_TX_CFG, MAC_TX_FCS_INS ) ) != 0u ) ) &&
            ( len < QSE_PAD_TO_LEN ) )
        {
            len = QSE_PAD_TO_LEN;
        }

        /* The FCS is appended after padding. */
        if( ( tx_cfg & QSE_MASK( MAC_TX_CFG, MAC_TX_FCS_INS ) ) != 0u )
        {
            len = (uint16_t)( len + QSE_FCS_LEN );
        }

        if( wire_len != NULL_U16 )
        {
            *wire_len = len;
        }

        if( rx_len != NULL_U16 )
        {
            /* The receiver optionally strips the FCS before the frame reaches
             * AXI4-Stream, reducing the length the DMA must be armed for.
             */
            if( ( ( rx_cfg & QSE_MASK( MAC_RX_CFG, MAC_RX_FCS_RMV ) ) != 0u ) &&
                ( len >= QSE_FCS_LEN ) )
            {
                *rx_len = (uint16_t)( len - QSE_FCS_LEN );
            }
            else
            {
                *rx_len = len;
            }
        }

        status = QSE_OK;
    }

    return ( status );
}

/*******************************************************************************
 * QSE_tx_enable()
 */
void
QSE_tx_enable
(
    QSE_instance_t * this_qse
)
{
    HAL_ASSERT( this_qse != NULL_INSTANCE );

    if( this_qse != NULL_INSTANCE )
    {
        this_qse->tx_cfg_shadow = HAL_get_32bit_reg( this_qse->base_address,
                                              COREQSE_REG_MAP_MAC_TX_CFG );

        this_qse->tx_cfg_shadow |= QSE_MASK( MAC_TX_CFG, MAC_TX_EN );

        HAL_set_32bit_reg( this_qse->base_address,
                           COREQSE_REG_MAP_MAC_TX_CFG,
                           this_qse->tx_cfg_shadow );
    }
}

