/*******************************************************************************
 * QSE_phy_verify_mdio()
 */
uint8_t
QSE_phy_verify_mdio
(
    const QSE_instance_t * this_qse,
    uint16_t               readings[4]
)
{
    MDIO_instance_t mdio;
    uint8_t         mdio_status;

    HAL_ASSERT( this_qse != NULL_INSTANCE );

    if( this_qse == NULL_INSTANCE )
    {
        return ( QSE_ERR_PARAM );
    }

    if( this_qse->mdio_base_address == 0u )
    {
        return ( QSE_ERR_NOT_SUPPORTED );
    }

    mdio.base_address = this_qse->mdio_base_address;

    mdio_status = MDIO_self_test( &mdio, this_qse->phy_addr, readings );

    /* MDIO_ERR_CONSTANT and MDIO_ERR_NO_PHY both mean the readings cannot be
     * trusted, so both map to QSE_ERR. The caller can call MDIO_self_test()
     * directly if it needs to distinguish them, as the test application does in
     * order to print a specific diagnosis.
     */
    return ( qse_map_mdio_status( mdio_status ) );
}

