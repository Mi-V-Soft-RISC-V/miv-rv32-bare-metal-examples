/*******************************************************************************
 * QSE_pcs_get_sync_status()
 *
 * CoreQSE has no PCS status register. The SYNC and PCS_RX_SYNC_FSM_CUR_STATE
 * outputs are hardware ports only. This samples the PCS error counters twice
 * and reports stability, which is an indirect indication.
 */
uint8_t
QSE_pcs_get_sync_status
(
    QSE_instance_t * this_qse
)
{
#if ( COREQSE_CFG_STATS == 0u )
    ( void ) this_qse;

    /* No software visible link indication exists in this build. */
    return ( 0u );
#else
    uint8_t           status = 0u;
    uint32_t          code_first;
    uint32_t          sync_first;
    uint32_t          code_second;
    uint32_t          sync_second;
    volatile uint32_t loop;

    HAL_ASSERT( this_qse != NULL_INSTANCE );

    if( this_qse != NULL_INSTANCE )
    {
        code_first = HAL_get_32bit_reg( this_qse->base_address,
                                        COREQSE_REG_MAP_PCS_CODE_ERR );
        sync_first = HAL_get_32bit_reg( this_qse->base_address,
                                        COREQSE_REG_MAP_PCS_SYNC_LOST_ERR );

        for( loop = 0u; loop < QSE_LINK_SETTLE_LOOPS; loop++ )
        {
            /* Allow any instability to accumulate in the counters. */
        }

        code_second = HAL_get_32bit_reg( this_qse->base_address,
                                         COREQSE_REG_MAP_PCS_CODE_ERR );
        sync_second = HAL_get_32bit_reg( this_qse->base_address,
                                         COREQSE_REG_MAP_PCS_SYNC_LOST_ERR );

        if( ( code_second == code_first ) && ( sync_second == sync_first ) )
        {
            status = 1u;
        }
    }

    return ( status );
#endif
}

/*******************************************************************************
 * QSE_self_test()
 */
uint8_t
QSE_self_test
(
    const QSE_instance_t * this_qse,
    uint32_t             * failed_offset
)
{
    uint8_t  status = QSE_ERR_PARAM;
    uint32_t reg_value;

    HAL_ASSERT( this_qse != NULL_INSTANCE );

    if( this_qse != NULL_INSTANCE )
    {
        status = QSE_OK;

        if( failed_offset != NULL_U32 )
        {
            *failed_offset = QSE_NO_FAILED_OFFSET;
        }

        /* CORE_VER bits [15:0] are reserved and must read as zero. */
        reg_value = HAL_get_32bit_reg( this_qse->base_address,
                                       COREQSE_REG_MAP_CORE_VER );

        if( ( reg_value & QSE_VER_RESERVED_MASK ) != 0u )
        {
            if( failed_offset != NULL_U32 )
            {
                *failed_offset = COREQSE_REG_MAP_CORE_VER_REG_OFFSET;
            }
            status = QSE_ERR;
        }

        /* MAC_TX_CFG reset value, ignoring MAC_TX_EN which QSE_init() clears
         * and which may legitimately be toggled at run time.
         */
        if( status == QSE_OK )
        {
            reg_value = HAL_get_32bit_reg( this_qse->base_address,
                                           COREQSE_REG_MAP_MAC_TX_CFG );

            if( ( reg_value & ~QSE_MASK( MAC_TX_CFG, MAC_TX_EN ) ) !=
                ( QSE_RESET_MAC_TX_CFG
                              & ~QSE_MASK( MAC_TX_CFG, MAC_TX_EN ) ) )
            {
                if( failed_offset != NULL_U32 )
                {
                    *failed_offset = COREQSE_REG_MAP_MAC_TX_CFG_REG_OFFSET;
                }
                status = QSE_ERR;
            }
        }

        /* MAC_RX_CFG reset value, ignoring MAC_RX_EN. */
        if( status == QSE_OK )
        {
            reg_value = HAL_get_32bit_reg( this_qse->base_address,
                                           COREQSE_REG_MAP_MAC_RX_CFG );

            if( ( reg_value & ~QSE_MASK( MAC_RX_CFG, MAC_RX_EN ) ) !=
                ( QSE_RESET_MAC_RX_CFG
                              & ~QSE_MASK( MAC_RX_CFG, MAC_RX_EN ) ) )
            {
                if( failed_offset != NULL_U32 )
                {
                    *failed_offset = COREQSE_REG_MAP_MAC_RX_CFG_REG_OFFSET;
                }
                status = QSE_ERR;
            }
        }

        /* MAC_TX_PARAM1/2 and MAC_RX_PARAM1/2 are deliberately not checked.
         * They are read-only registers reporting the build-time configuration:
         *
         *   MAC_xX_PARAM2 = { 11'b0, PAUSE_EN, ECC_ENABLE, CHECK_LT,
         *                     PREAMBLE, RAM_TYPE, FIFO_MODE, FIFO_DEPTH }
         *
         * Their value depends on the IP configurator settings, so no constant
         * comparison is valid. The user guide's "Reset: 0x20" holds only for a
         * build with RAM_TYPE 0; an LSRAM build reads 0x00010020.
         */
    }

    return ( status );
}

