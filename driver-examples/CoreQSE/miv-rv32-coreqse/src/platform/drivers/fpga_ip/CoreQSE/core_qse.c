/*******************************************************************************
 * QSE_stats_are_clean()
 */
uint8_t
QSE_stats_are_clean
(
    const QSE_rx_stats_t * before,
    const QSE_rx_stats_t * after
)
{
    uint8_t status = QSE_ERR_PARAM;

    HAL_ASSERT( before != (const QSE_rx_stats_t *)0 );
    HAL_ASSERT( after  != (const QSE_rx_stats_t *)0 );

    if( ( before != (const QSE_rx_stats_t *)0 ) &&
        ( after  != (const QSE_rx_stats_t *)0 ) )
    {
        status = QSE_OK;

        if( ( after->rx_err_count        != before->rx_err_count        ) ||
            ( after->rx_length_long_err  != before->rx_length_long_err  ) ||
            ( after->rx_length_check_err != before->rx_length_check_err ) ||
            ( after->rx_length_short_err != before->rx_length_short_err ) ||
            ( after->rx_fcs_error_count  != before->rx_fcs_error_count  ) ||
            ( after->rx_frame_err        != before->rx_frame_err        ) ||
            ( after->rx_oversize_count   != before->rx_oversize_count   ) ||
            ( after->rx_drop_count       != before->rx_drop_count       ) )
        {
            status = QSE_ERR;
        }

        if( ( after->rx_fifo_ecc_sb_corr != before->rx_fifo_ecc_sb_corr ) ||
            ( after->rx_fifo_ecc_db_det  != before->rx_fifo_ecc_db_det  ) ||
            ( after->pcs_eb_ecc_sb_corr  != before->pcs_eb_ecc_sb_corr  ) ||
            ( after->pcs_eb_ecc_db_det   != before->pcs_eb_ecc_db_det   ) )
        {
            status = QSE_ERR;
        }

        /* The only available indication that the receive path lost alignment. */
        if( ( after->pcs_code_err_count  != before->pcs_code_err_count  ) ||
            ( after->pcs_sync_lost_count != before->pcs_sync_lost_count ) )
        {
            status = QSE_ERR;
        }
    }

    return ( status );
}

/*******************************************************************************
 * QSE_build_frame_header()
 */
uint16_t
QSE_build_frame_header
(
    uint8_t              * buffer,
    const uint8_t        * dest_mac,
    const uint8_t        * src_mac,
    uint16_t               ether_type,
    const QSE_instance_t * this_qse
)
{
    uint16_t bytes_written = 0u;
    uint8_t  idx;

    HAL_ASSERT( buffer != NULL_U8 );

    /* A source address is required either explicitly or via the instance. */
    if( ( buffer != NULL_U8 ) &&
        ( ( src_mac != NULL_CONST_U8 ) || ( this_qse != NULL_INSTANCE ) ) )
    {
        for( idx = 0u; idx < QSE_MAC_ADDR_LEN; idx++ )
        {
            if( dest_mac != NULL_CONST_U8 )
            {
                buffer[ idx ] = dest_mac[ idx ];
            }
            else
            {
                buffer[ idx ] = QSE_BROADCAST_BYTE;
            }
        }

        for( idx = 0u; idx < QSE_MAC_ADDR_LEN; idx++ )
        {
            if( src_mac != NULL_CONST_U8 )
            {
                buffer[ QSE_MAC_ADDR_LEN + idx ] = src_mac[ idx ];
            }
            else
            {
                buffer[ QSE_MAC_ADDR_LEN + idx ] = this_qse->mac_addr[ idx ];
            }
        }

        /* EtherType, most significant byte first on the wire. */
        buffer[ 12u ] = (uint8_t)( ( ether_type >> QSE_BYTE_SHIFT ) &
                                   QSE_BYTE_MASK );
        buffer[ 13u ] = (uint8_t)( ether_type & QSE_BYTE_MASK );

        bytes_written = QSE_ETH_HDR_LEN;
    }

    return ( bytes_written );
}

/*==============================================================================
 *              EXTERNAL PHY MANAGEMENT, MDIO / MII STATION
 *
 * These functions present PHY management as part of the CoreQSE API, in the
 * style of the CoreTSE driver, but CoreQSE contains NO MII management hardware.
 * Every function here delegates to core_mdio.c, which drives the separate
 * COREMDIO_APB IP. See the architectural note in core_qse.h.
 *
 * Each function builds a temporary MDIO_instance_t from the base address stored
 * by QSE_attach_mdio(). That keeps the CoreQSE instance self contained: the
 * application holds one object rather than two, which is the point of the
 * exercise.
 *============================================================================*/

/*! Build the transport instance from what QSE_attach_mdio() recorded. */
#define QSE_MDIO_FROM( QSE )    { ( QSE )->mdio_base_address }

/*! Translate an MDIO_* status into the QSE_* status space. */
static uint8_t qse_map_mdio_status( uint8_t mdio_status )
{
    uint8_t status;

    switch( mdio_status )
    {
        case MDIO_OK:
            status = QSE_OK;
            break;

        case MDIO_ERR_PARAM:
            status = QSE_ERR_PARAM;
            break;

        case MDIO_ERR_NO_PHY:
        case MDIO_ERR_CONSTANT:
        case MDIO_ERR_TIMEOUT:
        default:
            status = QSE_ERR;
            break;
    }

    return ( status );
}

/*******************************************************************************
 * QSE_attach_mdio()
 */
uint8_t
QSE_attach_mdio
(
    QSE_instance_t * this_qse,
    addr_t           mdio_base_addr,
    uint8_t          phy_addr,
    uint32_t         mdio_prescaler
)
{
    uint8_t         status = QSE_ERR_PARAM;
    MDIO_instance_t mdio;

    HAL_ASSERT( this_qse != NULL_INSTANCE );
    HAL_ASSERT( mdio_base_addr != 0u );
    HAL_ASSERT( phy_addr <= 31u );

    if( ( this_qse != NULL_INSTANCE ) && ( mdio_base_addr != 0u ) &&
        ( phy_addr <= 31u ) )
    {
        this_qse->mdio_base_address = mdio_base_addr;
        this_qse->phy_addr          = phy_addr;

        /* Initialize the transport. MDIO_init() also clamps the prescaler to a
         * value the IP actually decodes and clears the control register, so a
         * stale direction bit from a previous run cannot corrupt the first read.
         */
        status = qse_map_mdio_status(
                     MDIO_init( &mdio, mdio_base_addr, mdio_prescaler ) );
    }

    return ( status );
}

/*******************************************************************************
 * QSE_read_phy_reg()
 */
uint8_t
QSE_read_phy_reg
(
    const QSE_instance_t * this_qse,
    uint8_t                reg_addr,
    uint16_t             * data
)
{
    MDIO_instance_t mdio;

    HAL_ASSERT( this_qse != NULL_INSTANCE );

    if( ( this_qse == NULL_INSTANCE ) || ( data == NULL_U16 ) )
    {
        return ( QSE_ERR_PARAM );
    }

    if( this_qse->mdio_base_address == 0u )
    {
        return ( QSE_ERR_NOT_SUPPORTED );
    }

    mdio.base_address = this_qse->mdio_base_address;

    return ( qse_map_mdio_status(
                 MDIO_read( &mdio, this_qse->phy_addr, reg_addr, data ) ) );
}

